let currentLocale = 'es';
let currentTranslations = LOCALES.es;
let subscribers = [];

// Obtener idioma del usuario
export function getUserLocale() {
    try {
        const user = JSON.parse(localStorage.getItem('user') || '{}');
        return user.language || 'es';
    } catch {
        return 'es';
    }
}

// Establecer idioma
export function setLocale(locale) {
    if (!LOCALES[locale]) {
        console.warn(`⚠️ [i18n] Idioma "${locale}" no encontrado, usando español`);
        locale = 'es';
    }
    
    currentLocale = locale;
    currentTranslations = LOCALES[locale] || LOCALES.es;
    
    // Guardar en localStorage
    try {
        const user = JSON.parse(localStorage.getItem('user') || '{}');
        user.language = locale;
        localStorage.setItem('user', JSON.stringify(user));
    } catch {}
    
    // Notificar suscriptores
    subscribers.forEach(callback => callback(locale));
    
    // Actualizar atributo HTML
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === 'ar' ? 'rtl' : 'ltr';
    
    console.log(`🌐 [i18n] Idioma cambiado a: ${LOCALES[locale]?.name || locale}`);
}

// Traducir una clave
export function t(key, params = {}) {
    let text = currentTranslations[key];
    
    if (!text) {
        console.warn(`⚠️ [i18n] Clave no encontrada: "${key}"`);
        return key;
    }
    
    // Reemplazar parámetros {n}
    for (const [param, value] of Object.entries(params)) {
        text = text.replace(`{${param}}`, value);
    }
    
    return text;
}

// Suscribirse a cambios de idioma
export function onLocaleChange(callback) {
    subscribers.push(callback);
    return () => {
        subscribers = subscribers.filter(cb => cb !== callback);
    };
}

// Obtener lista de idiomas disponibles
export function getAvailableLocales() {
    return Object.keys(LOCALES).map(key => ({
        code: key,
        name: LOCALES[key].name,
        flag: LOCALES[key].flag
    }));
}

// Inicializar
export function initI18n() {
    const locale = getUserLocale();
    setLocale(locale);
    console.log(`🌐 [i18n] Inicializado con idioma: ${LOCALES[locale]?.name || locale}`);
}

