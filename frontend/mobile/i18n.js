// Traducir elementos con data-i18n
export function translateDOM() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n');
        const text = t(key);
        if (text && text !== key) {
            // Si el elemento tiene hijos (como iconos), solo reemplazar el texto
            const hasChildElements = el.querySelector('i, span, img, .required, .tab-badge, .badge-count');
            if (hasChildElements) {
                const childNodes = el.childNodes;
                for (const node of childNodes) {
                    if (node.nodeType === Node.TEXT_NODE) {
                        node.textContent = text;
                        break;
                    }
                }
            } else {
                el.textContent = text;
            }
        }
    });
}

// Traducir placeholders
export function translatePlaceholders() {
    const elements = document.querySelectorAll('[data-i18n-placeholder]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const text = t(key);
        if (text && text !== key) {
            el.placeholder = text;
        }
    });
}

// Traducir títulos
export function translateTitles() {
    const elements = document.querySelectorAll('[data-i18n-title]');
    elements.forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const text = t(key);
        if (text && text !== key) {
            el.title = text;
        }
    });
}

// Traducir todo
export function translateAll() {
    translateDOM();
    translatePlaceholders();
    translateTitles();
    
    // Disparar evento personalizado
    document.dispatchEvent(new CustomEvent('i18n:updated', { 
        detail: { locale: currentLocale } 
    }));
}

